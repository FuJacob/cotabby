import Foundation

/// Decides which clipboard contents may become prompt context, and how Cotabby marks the completion
/// it briefly places on the pasteboard itself.
///
/// Password managers and clipboard tools follow the nspasteboard.org conventions: a copy that is a
/// secret, a one-off, or machine-generated carries a marker type next to its real data, and every
/// other clipboard reader is expected to leave it alone. Cotabby reads the clipboard for prompts, so
/// it honours those markers the same way clipboard managers do. A copied password or one-time code
/// would otherwise sit in the prompt (and, with the endpoint engine, reach a server) for as long as
/// the relevance window keeps it.
///
/// Kept pure, on raw type identifiers rather than `NSPasteboard`, so the rules are testable without a
/// pasteboard and usable from both the reader (`ClipboardContextProvider`) and the writer
/// (`SuggestionInserter`'s paste path).
nonisolated enum ClipboardPrivacyPolicy {
    /// The copy is a secret (password managers set it on every copied credential).
    static let concealedType = "org.nspasteboard.ConcealedType"
    /// The copy is a short-lived hand-off that its writer will replace or restore.
    static let transientType = "org.nspasteboard.TransientType"
    /// The copy was produced by a program, not chosen by the user.
    static let autoGeneratedType = "org.nspasteboard.AutoGeneratedType"

    /// Marker types that keep a copy out of prompt context. The three nspasteboard.org markers, plus
    /// the older vendor-specific types some password managers still write instead of them.
    static let contextExcludingTypes: Set<String> = [
        concealedType,
        transientType,
        autoGeneratedType,
        "de.petermaurer.TransientPasteboardType",
        "com.agilebits.onepassword",
        "net.antelle.keeweb"
    ]

    /// Markers Cotabby adds to the completion it puts on the pasteboard to drive a paste insert. The
    /// completion is there for a few hundred milliseconds before the user's clipboard is restored, so
    /// it is transient; it is also concealed because it was built from the user's typing and screen,
    /// which a clipboard history should not keep.
    static let markersForCotabbyPasteWrites = [transientType, concealedType]

    /// True when `pasteboardTypes` (raw type identifiers) carry any marker that keeps the copy out of
    /// prompts. The whole pasteboard is skipped, not just its text: an image or file from a
    /// concealed copy is just as private.
    static func excludesContext(pasteboardTypes: [String]) -> Bool {
        pasteboardTypes.contains(where: contextExcludingTypes.contains)
    }

    /// Clipboard text with secret-shaped spans (keys, tokens, card numbers) replaced, or nil when
    /// nothing but redactions and punctuation would remain.
    ///
    /// Runs on the raw text, before `PromptContextSanitizer`: the sanitizer turns `-`, `_` and `/`
    /// into spaces, which would split a key into pieces too short for the scrubber to recognise. An
    /// all-secret clipboard is dropped rather than sent as a bare marker, which a small model could
    /// copy into the completion.
    static func promptSafeText(_ text: String) -> String? {
        let redacted = TypingHistoryScrubber.redactSecrets(in: text)
        let remainder = redacted.replacingOccurrences(of: TypingHistoryScrubber.redaction, with: " ")
        guard remainder.contains(where: { $0.isLetter || $0.isNumber }) else {
            return nil
        }
        return redacted
    }
}
